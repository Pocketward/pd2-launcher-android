#!/usr/bin/env python3
"""Generates FEX's table of Android-blocked arm64 host syscalls (FEX patch 0001).

Inputs:
  blocked-host-syscalls.txt, every aarch64 syscall that the Android app seccomp policy does not allow.
  blocked-host-syscalls-eperm.txt, the blocked names answered with -EPERM; all others get -ENOSYS.
  FEX-2609.1 Source/Tools/LinuxEmulation/LinuxSyscalls/Arm64/SyscallsEnum.h (optional, --fex): every
  name must be a real arm64 syscall there.

Output (stdout), sorted by name:
  --format fex (default)  the body of Source/Tools/LinuxEmulation/LinuxSyscalls/Android/BlockedHostSyscalls.inl,
                          one ANDROID_BLOCKED_HOST_SYSCALL(name, ERRNO) per blocked syscall
  --format names          one "<name> <ENOSYS|EPERM>" per line
  --format numbers        one "<arm64 number> <name>" per line (needs --fex; the numbers come from FEX's
                          Arm64/SyscallsEnum.h), for a seccomp filter that reproduces the app policy.

  gen-blocked-host-syscalls.py [--blocked <list>] [--eperm <list>] [--fex <FEX source tree>]
                               [--format fex|names|numbers]
"""
import argparse
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent


def names_from_list(path):
    names = []
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            names.append(line)
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--blocked", type=pathlib.Path, default=HERE / "blocked-host-syscalls.txt")
    ap.add_argument("--eperm", type=pathlib.Path, default=HERE / "blocked-host-syscalls-eperm.txt")
    ap.add_argument("--fex", type=pathlib.Path, help="FEX source tree; checks every name against its Arm64 enum")
    ap.add_argument("--format", choices=("fex", "names", "numbers"), default="fex")
    args = ap.parse_args()
    if args.format == "numbers" and not args.fex:
        sys.exit("--format numbers needs --fex")

    blocked = names_from_list(args.blocked)
    if not blocked:
        sys.exit(f"{args.blocked}: no syscall names")
    if len(blocked) != len(set(blocked)):
        sys.exit(f"{args.blocked}: duplicate names in the blocked list")
    eperm = names_from_list(args.eperm)
    unknown = sorted(set(eperm) - set(blocked))
    if unknown:
        sys.exit(f"{args.eperm}: not in the blocked list: {' '.join(unknown)}")

    if args.fex:
        enum = (args.fex / "Source/Tools/LinuxEmulation/LinuxSyscalls/Arm64/SyscallsEnum.h").read_text()
        numbered = {name: int(nr) for name, nr in re.findall(r"SYSCALL_Arm64_(\w+) = (\d+),", enum)}
        missing = sorted(set(blocked) - set(numbered))
        if missing:
            sys.exit(f"not arm64 syscalls in FEX's SyscallsEnum.h: {' '.join(missing)}")

    answer = {name: "EPERM" if name in eperm else "ENOSYS" for name in blocked}
    if args.format == "names":
        sys.stdout.write("".join(f"{name} {answer[name]}\n" for name in sorted(blocked)))
        return
    if args.format == "numbers":
        sys.stdout.write("".join(f"{numbered[name]} {name}\n" for name in sorted(blocked)))
        return

    # This header is part of the .inl that patch 0001 adds; build.sh compares the two byte for byte.
    out = [
        "// Generated by android/userland/fex/gen-blocked-host-syscalls.py (pd2launcher). Do not edit.",
        "// Source: PROVENANCE.md section 1.3, the arm64 syscalls that the Android 13 (API 33) app seccomp",
        "// policy blocks (AOSP bionic android13-release); answers from blocked-host-syscalls-eperm.txt.",
        f"// {len(blocked)} syscalls.",
    ]
    for name in sorted(blocked):
        out.append(f"ANDROID_BLOCKED_HOST_SYSCALL({name}, {answer[name]})")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
