#!/usr/bin/env bash
# Fetches the pinned Debian 13 arm64 packages and extracts them, without maintainer scripts.
#
#   fetch-debian.sh            download what packages.lock names (SHA-256 checked), extract
#   fetch-debian.sh --resolve  first resolve packages.txt into packages.lock (arm64 container, apt
#                              against the snapshot, empty dpkg status so the closure is complete)
#
# Output (in the cache): work/staging  runtime packages, the start of the App userland tree
#                        work/sysroot  runtime + build packages, the cross-build sysroot
set -euo pipefail
export LC_ALL=C

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=config.sh
. "$here/config.sh"

# --- inside the arm64 resolver container -------------------------------------------------
if [[ "${1:-}" == --in-resolver ]]; then
    snapshot_sources > /etc/apt/sources.list.d/debian.sources
    apt-get update -qq
    mapfile -t runtime < <(awk '$1 == "runtime" {print $2}' /src/packages.txt)
    mapfile -t build < <(awk '$1 == "build" {print $2}' /src/packages.txt)
    mapfile -t exclude < <(awk '$1 == "exclude" {print $2}' /src/packages.txt)
    # The dpkg status apt resolves against: nothing installed except the excluded packages, which
    # are marked installed without their dependencies, so neither they nor what only they pull in
    # enter the closure.
    : > /tmp/status
    if [[ ${#exclude[@]} -gt 0 ]]; then
        apt-cache show --no-all-versions "${exclude[@]}" \
            | grep -Ev '^(Depends|Pre-Depends|Recommends|Suggests|Breaks|Conflicts):' \
            | sed 's/^Package: .*/&\nStatus: install ok installed/' > /tmp/status
    fi
    apt_opts=(-o Dir::State::status=/tmp/status
        -o APT::Install-Recommends=false -o APT::Install-Suggests=false)
    closure() {
        # Prints: <set> <package> <version> <arch> <sha256> <size> <url>, one line per package.
        local set="$1"; shift
        local -A urls=()
        local url file rest name version arch sha size filename
        local -a wanted=()
        # --print-uris gives the URL per pool file (but only an MD5); the simulation gives exact
        # versions; one apt-cache call gives SHA-256, size and pool file name for all of them.
        while read -r url file rest; do
            url="${url//\'/}"
            file="$(basename "$url")"
            urls["$(printf '%b' "${file//%/\\x}")"]="$url" # key: the URL-decoded pool file name
        done < <(apt-get -qq --print-uris "${apt_opts[@]}" install "$@")
        while read -r name version arch; do
            wanted+=("$name=$version")
        done < <(apt-get -s "${apt_opts[@]}" install "$@" \
            | sed -n 's/^Inst \([^ ]*\) (\([^ ]*\) [^[]*\[\([^]]*\)\]).*/\1 \2 \3/p')
        while read -r name version arch sha size filename; do
            url="${urls[$(basename "$filename")]:-}"
            [[ -n "$sha" && -n "$size" && -n "$url" ]] || { echo "incomplete record for $name $version" >&2; exit 1; }
            printf '%s %s %s %s %s %s %s\n' "$set" "$name" "$version" "$arch" "$sha" "$size" "$url"
        done < <(apt-cache show --no-all-versions "${wanted[@]}" | awk '
            /^Package: /  {p=$2} /^Version: / {v=$2} /^Architecture: / {a=$2}
            /^SHA256: /   {s=$2} /^Size: /    {z=$2} /^Filename: /     {f=$2}
            /^$/ { if (p != "") print p, v, a, s, z, f; p="" }
            END  { if (p != "") print p, v, a, s, z, f }')
        [[ ${#wanted[@]} -gt 0 ]]
    }
    closure runtime "${runtime[@]}" | sort -k2,2 > /tmp/runtime.lock
    closure build "${runtime[@]}" "${build[@]}" | sort -k2,2 > /tmp/all.lock
    {
        echo "# Generated by fetch-debian.sh --resolve from packages.txt; snapshot $DEBIAN_SNAPSHOT, arch arm64."
        echo "# <set> <package> <version> <arch> <sha256> <size> <url>"
        cat /tmp/runtime.lock
        # build = closure of runtime+build minus the runtime closure
        join -v1 -1 2 -2 2 -o 1.1,1.2,1.3,1.4,1.5,1.6,1.7 /tmp/all.lock /tmp/runtime.lock
    } > /cache/packages.lock.new
    exit 0
fi

# --- inside the tools container: download, verify, extract -----------------------------
if [[ "${1:-}" == --in-tools ]]; then
    debs=/cache/debs
    work=/cache/work
    mkdir -p "$debs"
    rm -rf "$work/staging" "$work/sysroot"
    mkdir -p "$work/staging" "$work/sysroot"

    extract() { # deb, root
        dpkg-deb --fsys-tarfile "$1" | tar -x --no-same-owner -p -C "$2"
    }
    usrmerge() { # root: fold /bin /sbin /lib into /usr and leave the aliasing symlinks
        local root="$1" d
        for d in bin sbin lib; do
            mkdir -p "$root/usr/$d"
            if [[ -d "$root/$d" && ! -L "$root/$d" ]]; then
                cp -a "$root/$d/." "$root/usr/$d/"
                rm -rf "${root:?}/$d"
            fi
            ln -sfn "usr/$d" "$root/$d"
        done
    }

    grep -v '^#' /src/packages.lock | while read -r set name version arch sha size url; do
        file="$debs/$(basename "$url")"
        if [[ ! -f "$file" ]] || ! echo "$sha  $file" | sha256sum -c --quiet - 2>/dev/null; then
            curl -fsSL --retry 3 -o "$file.part" "$url"
            mv "$file.part" "$file"
        fi
        echo "$sha  $file" | sha256sum -c --quiet - || { echo "SHA-256 mismatch: $name $version" >&2; exit 1; }
        [[ "$(stat -c %s "$file")" == "$size" ]] || { echo "size mismatch: $name" >&2; exit 1; }
        [[ "$set" == runtime ]] && extract "$file" "$work/staging"
        extract "$file" "$work/sysroot"
    done
    usrmerge "$work/staging"
    usrmerge "$work/sysroot"
    relativize_symlinks "$work/staging"
    relativize_symlinks "$work/sysroot"
    echo "staging: $(find "$work/staging" | wc -l) entries; sysroot: $(find "$work/sysroot" | wc -l) entries"
    exit 0
fi

# --- on the host ---------------------------------------------------------------------------
if [[ "${PD2_USERLAND_IN_CONTAINER:-}" == 1 ]]; then
    echo "refusing: unknown in-container mode" >&2
    exit 1
fi
engine="$(container_engine)"
mkdir -p "$USERLAND_CACHE"

if [[ "${1:-}" == --resolve || ! -f "$here/packages.lock" ]]; then
    rm -f "$USERLAND_CACHE/packages.lock.new"
    "$engine" run --rm --platform linux/arm64 \
        -v "$here:/src:ro" -v "$USERLAND_CACHE:/cache" \
        -e PD2_USERLAND_IN_CONTAINER=1 -e PD2_USERLAND_CACHE=/cache \
        "$DEBIAN_IMAGE" bash /src/fetch-debian.sh --in-resolver
    mv "$USERLAND_CACHE/packages.lock.new" "$here/packages.lock"
    echo "wrote $here/packages.lock ($(grep -vc '^#' "$here/packages.lock") packages)"
fi

run_in_tools fetch-debian.sh --in-tools
